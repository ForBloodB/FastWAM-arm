def axis_angle_to_matrix(vector):
    angle = float(np.linalg.norm(vector))
    if angle < 1e-12:
        return np.eye(3)
    x, y, z = np.asarray(vector, dtype=float) / angle
    skew = np.array([[0., -z, y], [z, 0., -x], [-y, x, 0.]])
    return np.eye(3) + math.sin(angle) * skew + (1. - math.cos(angle)) * (skew @ skew)


def solve_ik_6d(mujoco, model, data, site, target_pos, target_rot, qpos_addr, dof_addr, limits):
    saved = data.qpos.copy()
    q = np.array([data.qpos[index] for index in qpos_addr])
    for iteration in range(100):
        data.qpos[qpos_addr] = q
        mujoco.mj_forward(model, data)
        position = data.site_xpos[site].copy()
        rotation = data.site_xmat[site].reshape(3, 3).copy()
        position_error = target_pos - position
        trace = np.clip((np.trace(target_rot @ rotation.T) - 1.) / 2., -1., 1.)
        # rotation_to_axis_angle is equivalent for the small residuals used here.
        relative = target_rot @ rotation.T
        angle = math.acos(trace)
        if angle < 1e-10:
            rotation_error = np.zeros(3)
        elif abs(math.pi - angle) < 1e-5:
            rotation_error = np.zeros(3)
        else:
            rotation_error = np.array([relative[2, 1] - relative[1, 2], relative[0, 2] - relative[2, 0],
                                       relative[1, 0] - relative[0, 1]]) * angle / (2. * math.sin(angle))
        pos_residual = float(np.linalg.norm(position_error))
        rot_residual = float(np.linalg.norm(rotation_error))
        if pos_residual < .002 and rot_residual < .025:
            break
        jac_pos = np.zeros((3, model.nv))
        jac_rot = np.zeros((3, model.nv))
        mujoco.mj_jacSite(model, data, jac_pos, jac_rot, site)
        jacobian = np.vstack((jac_pos[:, dof_addr], .35 * jac_rot[:, dof_addr]))
        error = np.concatenate((position_error, .35 * rotation_error))
        delta = jacobian.T @ np.linalg.solve(jacobian @ jacobian.T + .008 ** 2 * np.eye(6), error)
        q = np.clip(q + np.clip(delta, -.05, .05), limits[:, 0] + 1e-4, limits[:, 1] - 1e-4)
    data.qpos[:] = saved
    mujoco.mj_forward(model, data)
    return q, {"iterations": iteration + 1, "position_residual_m": pos_residual,
               "rotation_residual_rad": rot_residual, "converged": bool(pos_residual < .005 and rot_residual < .06),
               "orientation_control": "full_6d_with_panda_to_b601_tool_alignment"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path("/home/aup/lerobot-fastwam"))
    parser.add_argument("--context", type=Path, required=True)
    parser.add_argument("--initial-q", type=Path, required=True,
                        help="JSON generated by the official Seeed Pinocchio full-pose solver")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--max-actions", type=int, default=32)
    parser.add_argument("--inference-steps", type=int, default=1)
    parser.add_argument("--physics-steps", type=int, default=250)
    args = parser.parse_args()
    root = args.root.resolve()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    os.environ.setdefault("DIFFSYNTH_MODEL_BASE_PATH", str(root / "checkpoints"))
    os.environ.setdefault("DIFFSYNTH_SKIP_DOWNLOAD", "true")
    os.environ.setdefault("MUJOCO_GL", "egl")
    sys.path.insert(0, str(root / "host"))
    sys.path.insert(0, str(root / "vendor/FastWAM-main/src"))

    import cv2
    import mujoco
    import torch
    from PIL import Image
    from fastwam_inference_smoke import _load_policy
    from fastwam_b601_adapter import adapt_libero_action_to_b601
    from b601_fastwam_sim import rotation_to_axis_angle, get_pose

    checkpoint = root / "checkpoints/fastwam_release/libero_optional_idm_2cam224.pt"
    stats = root / "checkpoints/fastwam_release/libero_optional_idm_2cam224_dataset_stats.json"
    scene = root / "sim_b601/official_fastwam/paper_box_basket.xml"
    cfg, policy, processor = _load_policy(root, checkpoint, stats, args.inference_steps)
    context_blob = torch.load(args.context, map_location="cpu", weights_only=True)
    context = context_blob["context"].to("cuda")
    context_mask = context_blob["context_mask"].to("cuda")
    prompt = str(context_blob["prompt"])

    model = mujoco.MjModel.from_xml_path(str(scene))
    data = mujoco.MjData(model)
    renderer = mujoco.Renderer(model, height=224, width=224)
    names = [f"joint{i}" for i in range(1, 7)]
    ids = [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name) for name in names]
    qpos_addr = [model.jnt_qposadr[i] for i in ids]
    dof_addr = [model.jnt_dofadr[i] for i in ids]
    limits = np.array([model.jnt_range[i] for i in ids])
    actuators = [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, f"{name}_motor") for name in names]
    grip_q = model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "joint7")]
    grip_dof = model.jnt_dofadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "joint7")]
    grip_act = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_ACTUATOR, "joint7_motor")
    left_q = model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "joint_left")]
    right_q = model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "joint_right")]
    site = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE, "b601_eef")
    box_body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "paper_box")
    # Columns are Panda tool axes expressed in the B601 gripper frame:
    # Panda +Z approach -> B601 +X approach; closing axes remain aligned.
    r_panda_to_b601 = np.array([[0., 0., 1.], [0., 1., 0.], [-1., 0., 0.]])
    kp = np.array([80., 100., 100., 35., 25., 18.])
    kd = np.array([8., 10., 10., 4., 3., 2.5])
    tau_limit = np.array([36., 36., 36., 14., 14., 14.])
    target_q = np.zeros(6)
    target_grip = 0.05

    def physics(count):
        for _ in range(count):
            q = data.qpos[qpos_addr]
            qd = data.qvel[dof_addr]
            tau = data.qfrc_bias[dof_addr] + kp * (target_q - q) - kd * qd
            data.ctrl[actuators] = np.clip(tau, -tau_limit, tau_limit)
            data.ctrl[grip_act] = np.clip(300. * (target_grip - data.qpos[grip_q]) - 120. * data.qvel[grip_dof], -150., 150.)
            mujoco.mj_step(model, data)

    def render(camera):
        renderer.update_scene(data, camera=camera)
        return renderer.render().copy()

    def contact_count():
        count = 0
        for index in range(data.ncon):
            contact = data.contact[index]
            first = model.geom(contact.geom1).name
            second = model.geom(contact.geom2).name
            pair = {first, second}
            if "paper_box_geom" in pair and any("gripper" in name for name in pair):
                count += 1
        return count

    mujoco.mj_resetData(model, data)
    initial_report = json.loads(args.initial_q.read_text())
    if not initial_report.get("success") or initial_report.get("position_only") is not False:
        raise RuntimeError(f"Official full-pose initial IK is not successful: {initial_report}")
    initial_q = np.asarray(initial_report["initial_q"], dtype=float)
    if initial_q.shape != (6,) or not np.isfinite(initial_q).all():
        raise RuntimeError(f"Invalid official initial_q: {initial_q}")
    data.qpos[qpos_addr] = initial_q
    mujoco.mj_forward(model, data)
    initial_target_position = np.asarray(initial_report["target_position_m"], dtype=float)
    initial_target_rotation = np.asarray(initial_report["target_rotation"], dtype=float)
    initial_position_error = float(np.linalg.norm(data.site_xpos[site] - initial_target_position))
    initial_relative_rotation = initial_target_rotation @ data.site_xmat[site].reshape(3, 3).T
    initial_trace = np.clip((np.trace(initial_relative_rotation) - 1.) / 2., -1., 1.)
    initial_rotation_error = float(math.acos(initial_trace))
    initial_ik = {"solver": initial_report["solver"], "source_json": str(args.initial_q),
                  "success": True, "error": initial_report["error"], "iterations": initial_report["iterations"],
                  "mujoco_position_residual_m": initial_position_error,
                  "mujoco_rotation_residual_rad": initial_rotation_error,
                  "orientation_control": "full_6d_with_panda_to_b601_tool_alignment"}
    if initial_position_error > .005 or initial_rotation_error > .06:
        raise RuntimeError(f"Official/MuJoCo tool-frame discrepancy: {initial_ik}")
    data.qpos[qpos_addr] = initial_q
    data.qpos[[grip_q, left_q, right_q]] = .05
    data.qvel[:] = 0.
    target_q = initial_q.copy()
    mujoco.mj_forward(model, data)
    physics(500)
    initial_box = data.xpos[box_body].copy()
    max_box_z = float(initial_box[2])
    state_key = processor.shape_meta["state"][0]["key"]
    action_key = processor.shape_meta["action"][0]["key"]
    normalizer = processor.normalizer.normalizers["action"][action_key]
    global_video = cv2.VideoWriter(str(out / "global.mp4"), cv2.VideoWriter_fourcc(*"mp4v"), 8, (224, 224))
    wrist_video = cv2.VideoWriter(str(out / "wrist.mp4"), cv2.VideoWriter_fourcc(*"mp4v"), 8, (224, 224))
    rows = []
    inference_times = []
    stop_reason = "max_actions"
    try:
        for step in range(args.max_actions):
            mujoco.mj_forward(model, data)
            external = render("global")
            wrist = render("wrist")
            Image.fromarray(external).save(out / f"step_{step:03d}_global.png")
            Image.fromarray(wrist).save(out / f"step_{step:03d}_wrist.png")
            global_video.write(cv2.cvtColor(external, cv2.COLOR_RGB2BGR))
            wrist_video.write(cv2.cvtColor(wrist, cv2.COLOR_RGB2BGR))
            eef_pos, eef_rot = get_pose(mujoco, model, data, site)
            panda_rot = eef_rot @ r_panda_to_b601.T
            raw_state = np.concatenate((eef_pos, rotation_to_axis_angle(panda_rot), data.qpos[[left_q, right_q]])).astype(np.float32)
            # Normalization must never alias or modify the physical state used by control.
            state_batch = {"state": {state_key: torch.from_numpy(raw_state.copy()).unsqueeze(0)}}
            normalized_state = processor.normalizer.forward(processor.action_state_transform(state_batch))["state"][state_key]
            combined = np.concatenate((external, wrist), axis=1)
            image = torch.from_numpy(combined).permute(2, 0, 1).unsqueeze(0).to(device="cuda", dtype=policy.torch_dtype)
            image = image * (2.0 / 255.0) - 1.0
            started = time.perf_counter()
            with torch.inference_mode():
                prediction = policy.infer_action(prompt=None, input_image=image, action_horizon=4,
                    context=context, context_mask=context_mask, proprio=normalized_state.to("cuda"),
                    num_inference_steps=args.inference_steps, seed=20261028 + step, rand_device="cpu",
                    compile_action_infer=False, action_infer_mode="first_frame", negative_prompt="",
                    text_cfg_scale=1.0, tiled=False)
            inference_s = time.perf_counter() - started
            inference_times.append(inference_s)
            actions = normalizer.backward(prediction["action"].detach().float().cpu()).numpy()
            if actions.ndim == 3 and actions.shape[0] == 1:
                actions = actions[0]
            if actions.shape != (4, 7) or not np.isfinite(actions).all():
                stop_reason = "invalid_model_action"
                break
            adapted = adapt_libero_action_to_b601(raw_state, actions[0],
                max_translation_step_m=.005, max_rotation_step_rad=math.radians(1.))
            target_panda_rot = axis_angle_to_matrix(adapted["axis_angle_rad"])
            # Inverse of panda_rot = b601_rot @ r_panda_to_b601.T.
            target_b601_rot = target_panda_rot @ r_panda_to_b601
            import subprocess
            ik_request = {"current_q": data.qpos[qpos_addr].tolist(),
                          "target_position_m": np.asarray(adapted["position_m"]).tolist(),
                          "target_rotation": target_b601_rot.tolist()}
            ik_env = os.environ.copy()
            ik_env["PYTHONPATH"] = "/home/aup/Workspace/reBotArm_control_py"
            ik_process = subprocess.run(
                ["/home/aup/Workspace/reBotArm_control_py/.venv/bin/python",
                 str(root / "sim_b601/official_fastwam/pinocchio_ik_step.py")],
                input=json.dumps(ik_request), capture_output=True, text=True, env=ik_env, timeout=30)
            if ik_process.returncode != 0:
                (out / "ik_failure.json").write_text(json.dumps({"request": ik_request,
                    "stderr": ik_process.stderr, "stdout": ik_process.stdout}, indent=2))
                stop_reason = "official_ik_process_failed"
                break
            ik = json.loads(ik_process.stdout)
            solution = np.asarray(ik["q"], dtype=float)
            ik["accepted_within_control_tolerance"] = bool(
                ik["position_residual_m"] <= .002 and ik["rotation_residual_rad"] <= .025)
            if not ik["accepted_within_control_tolerance"] or solution.shape != (6,) or not np.isfinite(solution).all():
                (out / "ik_failure.json").write_text(json.dumps({"request": ik_request, "result": ik,
                    "raw_state": raw_state.tolist(), "model_action": actions[0].tolist(), "adapted": adapted}, indent=2))
                stop_reason = "ik_failed"
                break
            current_q = data.qpos[qpos_addr].copy()
            target_q = current_q + np.clip(solution - current_q, -math.radians(1.), math.radians(1.))
            target_grip = 0.0 if adapted["gripper_intent"] == "close" else 0.05
            before_box = data.xpos[box_body].copy()
            physics(args.physics_steps)
            max_box_z = max(max_box_z, float(data.xpos[box_body][2]))
            contacts = contact_count()
            row = {"step": step, "prompt": prompt, "inference_seconds": inference_s,
                   "state": raw_state.tolist(), "action_chunk": actions.tolist(), "adapted": adapted,
                   "ik": ik, "target_q": target_q.tolist(), "actual_q": data.qpos[qpos_addr].tolist(),
                   "target_gripper": target_grip, "actual_gripper": data.qpos[[left_q, right_q]].tolist(),
                   "box_before": before_box.tolist(), "box_after": data.xpos[box_body].tolist(),
                   "gripper_box_contacts": contacts, "physics_steps": args.physics_steps}
            rows.append(row)
            (out / "transitions.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
            print(json.dumps({"step": step, "inference_s": round(inference_s, 4),
                              "tcp": data.site_xpos[site].tolist(), "box": data.xpos[box_body].tolist(),
                              "contacts": contacts}), flush=True)
        final_box = data.xpos[box_body].copy()
        in_basket = abs(final_box[0] - .50) < .065 and abs(final_box[1] - .09) < .055 and .11 < final_box[2] < .25
        lifted = max_box_z >= initial_box[2] + .06
        success = bool(in_basket and lifted)
        if success:
            stop_reason = "task_success"
        final_global = render("global")
        final_wrist = render("wrist")
        Image.fromarray(final_global).save(out / "final_global.png")
        Image.fromarray(final_wrist).save(out / "final_wrist.png")
        summary = {"system": "395 local FastWAM + official B601-RS MuJoCo dynamics",
                   "model_scene": str(scene), "model_source": "Seeed RS official ROS2 scene and LAN-GER RS MJCF baseline",
                   "checkpoint": checkpoint.name, "checkpoint_embodiment": "Panda/LIBERO zero-shot; not B601 fine-tuned",
                   "prompt": prompt, "device": torch.cuda.get_device_name(0), "actions_executed": len(rows),
                   "stop_reason": stop_reason, "mean_inference_seconds": float(np.mean(inference_times)) if inference_times else None,
                   "initial_box_m": initial_box.tolist(), "final_box_m": final_box.tolist(),
                   "max_box_z_m": max_box_z, "lifted_60mm": bool(lifted), "inside_basket": bool(in_basket),
                   "task_success": success, "success_criteria": "physical contact only; box lifted at least 60 mm and final center inside basket; no attachment or teleport",
                   "control": "official 7 torque actuators; gravity-compensated PD; 5 mm translation bound; 1 degree joint bound per policy step; Seeed Pinocchio full 6D IK",
                   "ik_execution_tolerance": "position <= 2 mm and rotation <= 0.025 rad; official converged flag and residuals retained per step",
                   "initial_pregrasp_ik": initial_ik,
                   "tool_alignment": "Panda +Z approach mapped to B601 +X approach; R=[[0,0,1],[0,1,0],[-1,0,0]]; state and target rotations converted explicitly",
                   "cross_embodiment_mapping_validated": False, "dataset_downloaded": False,
                   "physical_hardware_connected": False, "frames": "224x224 global and wrist PNG plus MP4; transitions.jsonl"}
        (out / "summary.json").write_text(json.dumps(summary, indent=2))
        print(json.dumps(summary, indent=2), flush=True)
    finally:
        global_video.release()
        wrist_video.release()
        renderer.close()


if __name__ == "__main__":
    main()
